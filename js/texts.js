window.synthesizeNatal = function synthesizeNatal(chart) {
  const t = window.ZENIT_TEXTS;
  const sun = t.sun[chart.sun.sign.key];
  const moon = t.moon[chart.moon.sign.key];
  const parts = [];
  parts.push(sun);
  parts.push(moon);
  if (chart.asc) parts.push(t.asc[chart.asc.key]);
  else if (chart.period) {
    parts.push("Точный час не указан. Выбран промежуток «" + chart.period.label + "». Асцендент не ставим. Луна посчитана на середину этого часа.");
  } else {
    parts.push("Час рождения не указан. Асцендент не ставим: без часа ось карты не закреплена. Солнце и Луна посчитаны.");
  }

  if (chart.sun.sign.key === chart.moon.sign.key) {
    parts.push("Солнце и Луна в одном знаке. То, что вы показываете, и то, что вам нужно для покоя, чаще совпадает. Из-за этого легко не заметить, что у других людей темп другой.");
  } else if (chart.sun.sign.element === chart.moon.sign.element) {
    parts.push("Солнце и Луна в одной стихии. Снаружи и внутри вы говорите на похожем языке. Вас проще понять, и вам проще не спорить с собой по мелочам.");
  } else {
    parts.push("Снаружи — " + chart.sun.sign.name + ", внутри — " + chart.moon.sign.name + ". Это два разных темпа в одном человеке, а не ошибка карты.");
  }

  parts.push("Это сочетание точек вашей карты, а не гороскоп одного знака.");
  parts.push("Сверьте его со своей неделей: где описание вам подходит, а где вы подстраиваетесь под знак.");
  return parts.join(" ");
};


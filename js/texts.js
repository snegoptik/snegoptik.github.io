window.synthesizeNatal = function synthesizeNatal(chart) {
  const t = window.ZENIT_TEXTS;
  const sun = t.sun[chart.sun.sign.key];
  const moon = t.moon[chart.moon.sign.key];
  const parts = [];
  parts.push(sun);
  parts.push(moon);
  if (chart.asc) parts.push(t.asc[chart.asc.key]);
  else {
    parts.push("Время рождения не указано, поэтому асцендент и дома я не рисую как точные: без часа ось карты плавает. Солнце и Луна при этом считаются уверенно.");
  }

  if (chart.sun.sign.key === chart.moon.sign.key) {
    parts.push("Солнце и Луна в одном знаке: то, что вы показываете, и то, что вам нужно для покоя, совпадает чаще, чем у многих. Это сила — и риск не замечать другие скорости.");
  } else if (chart.sun.sign.element === chart.moon.sign.element) {
    parts.push("Солнце и Луна одной стихии: внешнее и внутреннее говорят на похожем языке. Людям проще вас считать, вам — проще не спорить с собой по мелочам.");
  } else {
    parts.push("В вас сходятся две скорости: снаружи " + chart.sun.sign.name + ", внутри " + chart.moon.sign.name + ". Это не ошибка карты, а место, где вы учитесь не выбирать одно за счёт другого.");
  }

  parts.push("Это не гороскоп знака. Это сочетание точек вашей карты. Ниже — планеты и дома без замка на сам расчёт.");
  parts.push("Что из этого узнаёте в своей неделе — уже не вопрос к небу.");
  return parts.join(" ");
};


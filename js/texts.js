window.compatibilityThemes = function compatibilityThemes(a, b) {
  function rel(i, j) {
    const d = Math.abs(i - j);
    const m = Math.min(d, 12 - d);
    if (m === 0) return "рядом";
    if (m === 2) return "секстиль";
    if (m === 3) return "квадрат";
    if (m === 4) return "тригон";
    if (m === 6) return "оппозиция";
    return "нейтрально";
  }
  const sunR = rel(a.sun.sign.index, b.sun.sign.index);
  const moonR = rel(a.moon.sign.index, b.moon.sign.index);
  const themes = [];

  themes.push({
    title: "Где может быть легко",
    text: sunR === "тригон" || sunR === "секстиль" || sunR === "рядом"
      ? "Солнца говорят на похожем языке: цели и стиль жизни сами по себе не воюют. Мира это не гарантирует, но бытовых «зачем ты так» становится меньше."
      : sunR === "квадрат" || sunR === "оппозиция"
        ? "Солнца стоят в напряжении. Вам может быть нужен разный темп и разная степень заметности. Легче назвать это вслух, чем считать чужим характером."
        : "Солнца не спорят сами и не сливаются. Общий быт здесь собирается из привычек, а не из ощущения «нас создали друг для друга»."
  });

  themes.push({
    title: "Где может тереть",
    text: moonR === "квадрат" || moonR === "оппозиция"
      ? "Луны отдыхают по-разному. Кому-то нужны тишина и еда, кому-то — разговор или воздух. Отсюда часто бытовые ссоры. Это ещё не значит, что вы не пара."
      : moonR === "рядом" || moonR === "тригон"
        ? "Луны скорее слышат друг друга. Риск в другом: слишком быстро решить, что «нам и так всё ясно», и перестать уточнять."
        : "Способы отдыха разные, но не враждебные. Чужой отдых не стоит сразу читать как претензию."
  });

  themes.push({
    title: "Как разговаривать",
    text: "Не спорьте знаками. Спросите прямо, что нужно сегодня вечером: тишина, решение или близость. Карта показывает склонности. Реплики за вас она не пишет."
  });

  themes.push({
    title: "Чего не требовать",
    text: "Не ждите, что второй человек будет вашей Луной. " + a.sun.sign.name + " и " + b.sun.sign.name + " могут жить рядом, если не ставить условие «будь как я»."
  });

  return themes;
};

window.todayAccent = function todayAccent(chart, pack) {
  const dat = {
    Sun: "Солнцу", Moon: "Луне", Mercury: "Меркурию", Venus: "Венере",
    Mars: "Марсу", Jupiter: "Юпитеру", Saturn: "Сатурну", Asc: "асценденту"
  };
  const yours = {
    Sun: "вашему Солнцу", Moon: "вашей Луне", Mercury: "вашему Меркурию",
    Venus: "вашей Венере", Mars: "вашему Марсу", Jupiter: "вашему Юпитеру",
    Saturn: "вашему Сатурну", Asc: "вашему асценденту"
  };
  const hit = pack.hits && pack.hits[0];
  if (hit) {
    const hard = hit.type.key === "square" || hit.type.key === "opposition";
    const soft = hit.type.key === "trine" || hit.type.key === "sextile";
    const tone = hard
      ? "День скорее про трение и про то, где у вас предел."
      : soft
        ? "День скорее про опору: можно опереться на то, что уже умеете."
        : "Тема дня заметная: её трудно пропустить.";
    const to = dat[hit.natal.key] || hit.natal.ru;
    const yoursTo = yours[hit.natal.key] || ("вашему " + to);
    const today = hit.transit.key === "Moon" || hit.transit.key === "Venus"
      ? "Сегодняшняя"
      : hit.transit.key === "Sun"
        ? "Сегодняшнее"
        : "Сегодняшний";
    return {
      title: "Транзит · " + hit.transit.ru + " к " + to,
      text: today + " " + hit.transit.ru + " в аспекте «" + hit.type.ru + "» к " + yoursTo +
        ". " + tone
    };
  }
  const moon = pack.moon;
  return {
    title: "Луна сегодня · " + moon.sign.name,
    text: "Точного совпадения с вашей картой сейчас нет. Ориентир на ближайшие часы — Луна в знаке «" +
      moon.sign.name + "»: так вам сейчас легче восстановиться. Если своей карты ещё нет, ниже есть карта таро на сегодня."
  };
};


window.planetLine = function planetLine(p) {
  if (p.key === "Sun" || p.key === "Moon") return p.retrograde ? "ретроградность к светилам не относится" : "";
  const need = window.ZENIT_TEXTS.planetNeed[p.key];
  const how = window.ZENIT_TEXTS.signHow[p.sign.key];
  const loc = window.ZENIT_LOC[p.sign.key] || p.sign.name;
  const rx = p.retrograde ? " Ретроградность здесь — про пересмотр, не про поломку почты." : "";
  if (!need) return p.ru + " в " + loc + "." + rx;
  return p.ru + " в " + loc + " — " + need + " " + how + "." + rx;
};


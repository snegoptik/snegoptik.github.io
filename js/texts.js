  const soft = a.type.key === "trine" || a.type.key === "sextile";
  const hard = a.type.key === "square" || a.type.key === "opposition";
  const tone = soft ? "идёт легче" : hard ? "требует внимания, не приговора" : "звучит в одну точку";

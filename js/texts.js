window.renderFullReport = function renderFullReport(chart) {
  const byHouse = {};
  chart.positions.forEach(function (p) {
    (byHouse[p.house] = byHouse[p.house] || []).push(p);
  });
  let houses = "";
  for (let i = 1; i <= 12; i++) {
    const who = byHouse[i] ? byHouse[i].map(function (p) { return p.ru + " в " + (window.ZENIT_LOC[p.sign.key] || p.sign.name); }).join(", ") : "планет нет";
    houses += "<h3><a href=\"slovar/doma.html#dom-" + i + "\">" + i + " дом</a></h3><p>" + window.reportHouse[i] + "</p><p class=\"small\">Сейчас здесь: " + who + ".</p>";
  }
  const aspects = chart.aspects.slice(0, 10).map(function (a) {
    return "<li>" + aspectLine(a) + "</li>";
  }).join("");
  const planets = chart.positions.map(function (p) {
    const extra = planetLine(p);
    const rx = p.retrograde ? " Rx" : "";
    return "<p><strong>" + p.ru + rx + " · " + p.sign.name + " " + formatDeg(p.sign.degree) +
      (chart.unknownTime ? "" : ", " + p.house + " дом") + "</strong>" +
      (extra ? "<br /><span class=\"small\">" + extra + "</span>" : "") + "</p>";
  }).join("");

  return (
    "<h2>Три опоры</h2><p>" + synthesizeNatal(chart) + "</p>" +
    "<p class=\"small\">" + window.ZENIT_TEXTS.lifePath[chart.lifePath] + "</p>" +
    "<h2>Планеты</h2>" + planets +
    "<h2>Дома</h2>" +
    (chart.unknownTime
      ? "<p class=\"notice\">Без часа дома считаются от знака Солнца. Это схема, а не ось рождения.</p>"
      : "<p class=\"small\">Дома — целые знаки: первый дом совпадает со знаком асцендента.</p>") +
    houses +
    "<h2>Аспекты</h2>" +
    (aspects ? "<ul class=\"list-plain\">" + aspects + "</ul>" : "<p>Заметных аспектов почти нет.</p>") +
    "<h2>Что с этим делать</h2>" +
    "<p>Это не план на год. На неделе заметьте, где текст вам подходит, а где вы подгоняете себя под знак.</p>"
  );
};

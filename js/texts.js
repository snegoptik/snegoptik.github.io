window.compatibilityThemes = function compatibilityThemes(a, b) {
  function rel(i, j) {
    const d = Math.abs(i - j);
    const m = Math.min(d, 12 - d);
    if (m === 0) return "рядом";
    if (m === 2) return "секстиль";
    if (m === 3) return "квадрат";
    if (m === 4) return "тригон";
    if (m === 6) return "оппозиция";
    return "нейтрально";
  }
  const sunR = rel(a.sun.sign.index, b.sun.sign.index);
  const moonR = rel(a.moon.sign.index, b.moon.sign.index);
  const themes = [];

  themes.push({
    title: "Где может быть легко",
    text: sunR === "тригон" || sunR === "секстиль" || sunR === "рядом"
      ? "Солнца говорят на понятном языке: цели и стиль жизни не воюют сами по себе. Это не гарантия мира, но меньше бытовых недоразумений «зачем ты такой»."
      : sunR === "квадрат" || sunR === "оппозиция"
        ? "Солнца стоят в напряжении: вы можете хотеть разного темпа и разной видимости. Легче становится, когда это называют вслух, а не лечат характером."
        : "Солнца не спорят автоматически и не сливаются. Совместимость здесь собирается из привычек, не из «нас создали»."
  });

  themes.push({
    title: "Где может тереть",
    text: moonR === "квадрат" || moonR === "оппозиция"
      ? "Луны в разном ритме покоя. Один хочет тишины и еды, другой — разговора или воздуха. Это частая точка бытовых ссор, не доказательство «не пара»."
      : moonR === "рядом" || moonR === "тригон"
        ? "Луны скорее слышат друг друга. Риск другой: слишком быстро решать, что «нам и так всё ясно», и перестать уточнять."
        : "Эмоциональные языки разные, но не враждебные. Важно не переводить чужой способ отдыха в претензию."
  });

  themes.push({
    title: "Как разговаривать",
    text: "Не спорьте знаками. Спрашивайте конкретнее: чего человеку нужно сегодня вечером — тишины, решения или близости. Карта подсказывает склонности, не реплики за вас."
  });

  themes.push({
    title: "Чего не требовать",
    text: "Не требуйте, чтобы второй стал вашей Луной. " + a.sun.sign.name + " и " + b.sun.sign.name + " могут жить рядом, если не ставить ультиматум «будь как я». Это разбор тем, не вердикт «подходите / нет»."
  });

  return themes;
};

window.todayAccent = function todayAccent(chart, pack) {
  const dat = {
    Sun: "Солнцу", Moon: "Луне", Mercury: "Меркурию", Venus: "Венере",
    Mars: "Марсу", Saturn: "Сатурну", Asc: "асценденту"
  };
  const hit = pack.hits && pack.hits[0];
  if (hit) {
    const hard = hit.type.key === "square" || hit.type.key === "opposition";
    const soft = hit.type.key === "trine" || hit.type.key === "sextile";
    const tone = hard
      ? "День скорее про трение и ясность предела, не про разгон."
      : soft
        ? "День скорее про опору: можно опереться на то, что уже умеете."
        : "Тема звучит в одну точку — её трудно не заметить.";
    const to = dat[hit.natal.key] || hit.natal.ru;
    return {
      title: "Транзит · " + hit.transit.ru + " к " + to,
      text: "Сегодняшний " + hit.transit.ru + " делает " + hit.type.ru + " к вашему " + to +
        " (орб " + hit.orb.toFixed(1) + "°). " + tone + " Это акцент дня, не прогноз событий и не приговор карте."
    };
  }
  const moon = pack.moon;
  return {
    title: "Луна сегодня · " + moon.sign.name,
    text: "Точного мажорного транзита к вашей карте сейчас нет в узком орбисе. Ориентир дня — Луна в знаке «" +
      moon.sign.name + "»: как вам легче восстанавливаться ближайшие часы. Если своей карты ещё нет, хватит карты таро ниже."
  };
};

